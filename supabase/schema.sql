create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;
create schema if not exists private;

revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

create table if not exists public.staff_profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.salon_services (
  id uuid primary key default pg_catalog.gen_random_uuid(),
  name text not null unique check (length(btrim(name)) between 2 and 100),
  description text not null default '',
  price numeric(10, 2) not null check (price >= 0),
  duration_minutes integer not null check (duration_minutes between 5 and 600),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.customer_requests (
  id uuid primary key default pg_catalog.gen_random_uuid(),
  request_number bigint generated by default as identity unique,
  request_type text not null check (request_type in ('walk_in', 'appointment')),
  customer_name text not null check (length(btrim(customer_name)) between 2 and 120),
  customer_phone text not null check (length(btrim(customer_phone)) between 7 and 32),
  service_id uuid not null references public.salon_services (id) on delete restrict,
  service_name text not null,
  requested_date date,
  requested_time time,
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'serving', 'completed', 'cancelled')),
  receipt_token_hash text not null unique,
  created_at timestamptz not null default now(),
  constraint customer_request_schedule_matches_type check (
    (request_type = 'walk_in' and requested_date is null and requested_time is null)
    or
    (request_type = 'appointment' and requested_date is not null and requested_time is not null)
  )
);
alter table public.customer_requests
  drop constraint if exists appointment_date_not_in_past;

create index if not exists customer_requests_created_at_idx
  on public.customer_requests (created_at desc);
create index if not exists customer_requests_status_idx
  on public.customer_requests (status, created_at desc);

create or replace function private.is_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.staff_profiles
    where user_id = (select auth.uid())
  );
$$;

revoke all on function private.is_staff() from public, anon, authenticated;
grant execute on function private.is_staff() to authenticated;

alter table public.staff_profiles enable row level security;
alter table public.salon_services enable row level security;
alter table public.customer_requests enable row level security;

revoke all on table public.staff_profiles from public, anon, authenticated;
revoke all on table public.salon_services from public, anon, authenticated;
revoke all on table public.customer_requests from public, anon, authenticated;

grant select on table public.staff_profiles to authenticated;
grant select on table public.salon_services to anon, authenticated;
grant insert, update, delete on table public.salon_services to authenticated;
grant select on table public.customer_requests to authenticated;
grant update (status) on table public.customer_requests to authenticated;

drop policy if exists "Staff can read their own profile" on public.staff_profiles;
create policy "Staff can read their own profile"
  on public.staff_profiles
  for select
  to authenticated
  using (user_id = (select auth.uid()));

drop policy if exists "Visitors can read active salon services" on public.salon_services;
create policy "Visitors can read active salon services"
  on public.salon_services
  for select
  to anon, authenticated
  using (is_active);

drop policy if exists "Staff can manage salon services" on public.salon_services;
create policy "Staff can manage salon services"
  on public.salon_services
  for all
  to authenticated
  using ((select private.is_staff()))
  with check ((select private.is_staff()));

drop policy if exists "Staff can read customer requests" on public.customer_requests;
create policy "Staff can read customer requests"
  on public.customer_requests
  for select
  to authenticated
  using ((select private.is_staff()));

drop policy if exists "Staff can update customer request status" on public.customer_requests;
create policy "Staff can update customer request status"
  on public.customer_requests
  for update
  to authenticated
  using ((select private.is_staff()))
  with check ((select private.is_staff()));

create or replace function public.submit_customer_request(
  p_request_type text,
  p_customer_name text,
  p_customer_phone text,
  p_service_name text,
  p_requested_date date default null,
  p_requested_time time default null
)
returns table (
  receipt_token uuid,
  token_label text,
  request_status text
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_request_type text := pg_catalog.lower(pg_catalog.btrim(coalesce(p_request_type, '')));
  v_customer_name text := pg_catalog.btrim(coalesce(p_customer_name, ''));
  v_customer_phone text := pg_catalog.btrim(coalesce(p_customer_phone, ''));
  v_service public.salon_services%rowtype;
  v_receipt_token uuid := pg_catalog.gen_random_uuid();
  v_request_number bigint;
begin
  if v_request_type not in ('walk_in', 'appointment') then
    raise exception using errcode = '22023', message = 'Request type is invalid.';
  end if;

  if pg_catalog.length(v_customer_name) not between 2 and 120 then
    raise exception using errcode = '22023', message = 'Customer name is invalid.';
  end if;

  if pg_catalog.length(v_customer_phone) not between 7 and 32 then
    raise exception using errcode = '22023', message = 'Phone number is invalid.';
  end if;

  if v_request_type = 'appointment' then
    if p_requested_date is null or p_requested_time is null or p_requested_date < current_date then
      raise exception using errcode = '22023', message = 'Appointment date and time are invalid.';
    end if;
  elsif p_requested_date is not null or p_requested_time is not null then
    raise exception using errcode = '22023', message = 'Walk-in requests cannot include an appointment time.';
  end if;

  select *
  into v_service
  from public.salon_services
  where name = pg_catalog.btrim(coalesce(p_service_name, ''))
    and is_active;

  if not found then
    raise exception using errcode = '22023', message = 'Selected service is not available.';
  end if;

  insert into public.customer_requests (
    request_type,
    customer_name,
    customer_phone,
    service_id,
    service_name,
    requested_date,
    requested_time,
    receipt_token_hash
  )
  values (
    v_request_type,
    v_customer_name,
    v_customer_phone,
    v_service.id,
    v_service.name,
    p_requested_date,
    p_requested_time,
    pg_catalog.encode(
      extensions.digest(
        pg_catalog.convert_to(v_receipt_token::text, 'UTF8'),
        'sha256'
      ),
      'hex'
    )
  )
  returning request_number into v_request_number;

  return query
  select
    v_receipt_token,
    'T-' || v_request_number::text,
    'pending'::text;
end;
$$;

create or replace function public.get_public_request_status(p_receipt_token uuid)
returns table (
  token_label text,
  request_status text,
  request_type text,
  service_name text,
  requested_date date,
  requested_time time
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    'T-' || request_number::text,
    status,
    request_type,
    service_name,
    requested_date,
    requested_time
  from public.customer_requests
  where receipt_token_hash = pg_catalog.encode(
    extensions.digest(
      pg_catalog.convert_to(p_receipt_token::text, 'UTF8'),
      'sha256'
    ),
    'hex'
  );
$$;

revoke all on function public.submit_customer_request(text, text, text, text, date, time) from public, anon, authenticated;
grant execute on function public.submit_customer_request(text, text, text, text, date, time) to anon, authenticated;

revoke all on function public.get_public_request_status(uuid) from public, anon, authenticated;
grant execute on function public.get_public_request_status(uuid) to anon, authenticated;
